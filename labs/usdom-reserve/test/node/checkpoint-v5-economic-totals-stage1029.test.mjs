import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const root=new URL('../../../../',import.meta.url);
const read=p=>readFileSync(new URL(p,root),'utf8');
const statement=read('crates/dom-usdom-checkpoint-statement/src/lib.rs');
const outer=read('crates/dom-usdom-checkpoint-program/src/outer.rs');
const guest=read('crates/dom-usdom-checkpoint-outer-risc0-guest/src/main.rs');
const burn=read('crates/dom-usdom-finalized-burn-program/src/lib.rs');
const registry=read('labs/usdom-reserve/contracts/DOMCheckpointRegistry.sol');
const sdk=read('labs/usdom-reserve/sdk/checkpoint-registry.mjs');
const submission=read('labs/usdom-reserve/sdk/checkpoint-submission.mjs');
const v3='DOMCheckpointV3(bytes32 bridgeDomain,uint32 domNetworkMagic,uint16 nativeStateVersion,uint16 transitionBatchVersion,uint64 previousHeight,bytes32 previousBlock,bytes32 previousStateRoot,bytes32 previousContextHash,uint256 previousTotalDifficulty,uint64 domHeight,bytes32 domBlock,bytes32 domStateRoot,bytes32 domContextHash,uint256 domTotalDifficulty,uint128 totalIssued,uint128 totalBurned,uint64 confirmationHeight,bytes32 confirmationBlock,uint256 confirmationTotalDifficulty,uint64 confirmationTimestamp,uint256 ethereumChainId,address registry,bytes32 activationScheduleCommitment,bytes32 checkpointConfigHash)';
assert.equal((statement.match(new RegExp(v3.replace(/[.*+?^${}()|[\]\\]/g,'\\$&'),'g'))||[]).length,1);
assert.ok(registry.includes(v3)); assert.ok(sdk.includes(v3));
assert.match(statement,/CHECKPOINT_TRANSITION_BATCH_VERSION: u16 = 3/);
assert.match(statement,/CHECKPOINT_TRANSITION_BATCH_V5_VERSION: u16 = 4/);
assert.match(statement,/V5_MAGIC[^\n]+UDCPST05/);
assert.match(statement,/CHECKPOINT_STATEMENT_V5_BYTES[^\n]+CHECKPOINT_STATEMENT_V4_BYTES \+ 32/);
assert.match(statement,/CheckpointStatementV5::from_bytes\(&v4_bytes\)\.is_err/);
assert.match(statement,/CheckpointStatementV4::from_bytes\(&v5_bytes\)\.is_err/);
assert.match(outer,/target_total_issued != statement\.total_issued/);
assert.match(guest,/validate_checkpoint_outer_chain_v5/);
assert.match(burn,/checkpoint_statement\.total_issued != state\.total_issued/);
assert.match(registry,/uint128 public latestTotalIssued/);
assert.match(registry,/uint128 public previousTotalIssued/);
assert.match(registry,/checkpoint\.totalIssued < latestTotalIssued/);
assert.match(registry,/checkpoint\.totalBurned > checkpoint\.totalIssued/);
assert.match(registry,/latestTotalIssued = current\.totalIssued/);
assert.match(submission,/statementBytes=550/);
assert.match(submission,/statementMagic=Buffer\.from\('UDCPST05'/);
assert.match(submission,/totalIssued:readUnsigned\(bytes,518,16/);
assert.match(submission,/totalBurned:readUnsigned\(bytes,534,16/);
console.log('checkpoint V5 economic totals stage1029: ok');
